def esc_url_sym(sym):
    # для favicon: юникод в проценты
    return "".join(f"%{b:02X}" for b in sym.encode("utf-8"))

def build():
    os.makedirs(PLANETY, exist_ok=True)

    # index
    idx = INDEX_TMPL.format(v=V, cards=cards_html(None), disclaimer=DISCLAIMER_INDEX)
    with open(os.path.join(PLANETY, "index.html"), "w", encoding="utf-8") as f:
        f.write(idx)

    # pages
    n = len(PLANETS)
    for i, (slug, name, sym, sub, alt, img) in enumerate(PLANETS):
        prev_slug, prev_name = PLANETS[(i - 1) % n][0], PLANETS[(i - 1) % n][1]
        next_slug, next_name = PLANETS[(i + 1) % n][0], PLANETS[(i + 1) % n][1]
        secs = []
        for title, text in PAGES[slug]:
            secs.append(
                f'    <section class="sign-sec">\n'
                f'      <h2 class="sec-title">{title}</h2>\n'
                f'      <p>{text}</p>\n'
                f'    </section>'
            )
        page = PAGE_TMPL.format(
            name=name, sym=sym, sym_url=esc_url_sym(sym), sub=sub, alt=alt, img=img,
            v=V, sections="\n".join(secs),
            prev=prev_slug, prev_name=prev_name, next=next_slug, next_name=next_name,
        )
        d = os.path.join(PLANETY, slug)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "index.html"), "w", encoding="utf-8") as f:
            f.write(page)
